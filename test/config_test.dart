import 'package:ai_debug/ai_debug.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('authentication token is generated by default', () {
    final config = AiDebugConfig(appId: 'test');
    expect(config.token, hasLength(43));
    expect(config.validate, returnsNormally);
    expect(
      () => AiDebugConfig(appId: 'test', token: 'secret').validate(),
      returnsNormally,
    );
    expect(
      () => AiDebugConfig(appId: 'test', token: ' secret ').validate(),
      throwsArgumentError,
    );
  });

  test('LAN mode requires a strong token', () {
    expect(
      () => AiDebugConfig(
        appId: 'test',
        token: 'short',
        unsafeLan: true,
      ).validate(),
      throwsArgumentError,
    );
    expect(
      () => AiDebugConfig(
        appId: 'test',
        token: ''.padRight(32, 'x'),
        unsafeLan: true,
      ).validate(),
      returnsNormally,
    );
  });

  test('files require explicit roots', () {
    final config = AiDebugConfig(
      appId: 'test',
      features: AiDebugFeatures(files: true),
    );

    expect(config.validate, throwsArgumentError);
  });

  test('config equality includes feature flags and sets', () {
    final first = AiDebugConfig(
      appId: 'test',
      token: 'same',
      allowedHosts: {'a', 'b'},
    );
    final reordered = AiDebugConfig(
      appId: 'test',
      token: 'same',
      allowedHosts: {'b', 'a'},
    );
    final changed = AiDebugConfig(
      appId: 'test',
      token: 'same',
      features: AiDebugFeatures(automation: true),
    );

    expect(first.sameAs(reordered), isTrue);
    expect(first.sameAs(changed), isFalse);
  });

  test('copies caller-owned sets', () {
    final hosts = {'debug.local'};
    final origins = {'https://debug.local'};
    final config = AiDebugConfig(
      appId: 'test',
      allowedHosts: hosts,
      allowedOrigins: origins,
    );

    hosts.add('changed.local');
    origins.clear();
    expect(config.allowedHosts, {'debug.local'});
    expect(config.allowedOrigins, {'https://debug.local'});
    expect(() => config.allowedHosts.add('nope'), throwsUnsupportedError);
  });

  test('file roots require the files feature', () {
    expect(
      () => AiDebugConfig(appId: 'test', allowedFileRoots: {'/tmp'}).validate(),
      throwsArgumentError,
    );
  });

  test('text and allow-list limits are finite', () {
    expect(
      () => AiDebugConfig(appId: ''.padRight(129, 'a')).validate(),
      throwsArgumentError,
    );
    expect(
      () =>
          AiDebugConfig(appId: 'test', token: ''.padRight(513, 'x')).validate(),
      throwsArgumentError,
    );
    expect(
      () => AiDebugConfig(
        appId: 'test',
        allowedHosts: {for (var i = 0; i < 129; i++) 'host-$i'},
      ).validate(),
      throwsArgumentError,
    );
  });

  test('none and all constructors support selective feature gates', () {
    const allowed = AiDebugFeatures.none(resources: true);
    const limited = AiDebugFeatures.all(network: false, telemetry: false);

    expect(allowed.resources, isTrue);
    expect(allowed.logs, isFalse);
    expect(limited.network, isFalse);
    expect(limited.telemetry, isFalse);
    expect(limited.resources, isTrue);
  });

  test('automation settings are compared and bounded', () {
    final first = AiDebugConfig(
      appId: 'test',
      token: 'same',
      automation: const UiAutomationConfig(allowRawCoordinates: true),
    );
    final second = AiDebugConfig(appId: 'test', token: 'same');
    final invalid = AiDebugConfig(
      appId: 'test',
      automation: const UiAutomationConfig(
        limits: UiAutomationLimits(maxNodes: 10001),
      ),
    );

    expect(first.sameAs(second), isFalse);
    expect(invalid.validate, throwsArgumentError);
  });
}
